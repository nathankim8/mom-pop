import type { LocationDataProvider } from '../provider';
import type { GridCell, LngLat } from '../../types';
import { CANDIDATE_SITES, GRID_BOUNDS, GRID_STEP, isWater } from './laGeography';
import { generateCompetitors } from './competitors';
import { simulateSignals } from './model';

export function createSimulatedProvider(): LocationDataProvider {
  const competitors = generateCompetitors();
  const gridCache = new Map<string, GridCell[]>();

  return {
    info: {
      id: 'simulated',
      label: 'Simulated LA model',
      isSimulated: true,
      description:
        'All foot traffic, vehicle traffic and competitor data are generated by a simple model of LA activity hubs. ' +
        'They are illustrative estimates for prototyping — not observed counts.',
      coverage: null,
      timeVarying: true,
      provenance: { pedestrian: 'simulated', vehicle: 'simulated', competitors: 'simulated', timeOfDay: 'simulated' },
      pedestrianLabel: 'Simulated foot traffic',
      competitorLabel: 'Simulated food businesses',
    },

    async getActivityGrid(q) {
      const key = `${q.timeOfDay}-${q.day}`;
      const cached = gridCache.get(key);
      if (cached) return cached;
      const cells: GridCell[] = [];
      for (let lat = GRID_BOUNDS.south; lat <= GRID_BOUNDS.north; lat += GRID_STEP.lat) {
        for (let lng = GRID_BOUNDS.west; lng <= GRID_BOUNDS.east; lng += GRID_STEP.lng) {
          const position: LngLat = [lng, lat];
          if (isWater(position)) continue;
          cells.push({ position, ...simulateSignals(position, q) });
        }
      }
      gridCache.set(key, cells);
      return cells;
    },

    async getSignalsAt(position, q) {
      return simulateSignals(position, q);
    },

    async getCompetitors() {
      return competitors;
    },

    async getCandidateSites() {
      return CANDIDATE_SITES;
    },
  };
}
